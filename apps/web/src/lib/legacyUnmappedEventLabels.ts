const DROPPED_METHOD_PREFIXES = ["thread/realtime/"] as const;

function normalizeLegacyMethod(method: string): string {
  const trimmed = method.trim();
  return trimmed.replace(/^system[:/]/u, "");
}

export function isDroppedLegacyUnmappedMethod(method: string): boolean {
  const normalized = normalizeLegacyMethod(method);
  return (
    LEGACY_UNMAPPED_DROPPED_METHODS.has(normalized) ||
    DROPPED_METHOD_PREFIXES.some((prefix) => normalized.startsWith(prefix))
  );
}

export function legacyUnmappedMethodTitle(method: string): string {
  return (
    LEGACY_UNMAPPED_METHOD_TITLES[normalizeLegacyMethod(method)] ?? LEGACY_UNMAPPED_FALLBACK_TITLE
  );
}
